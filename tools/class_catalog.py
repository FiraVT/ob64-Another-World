#!/usr/bin/env python3
"""Decode every class in the ROM into a Markdown catalog.

    tools/class_catalog.py [rom] [out.md]      (defaults: assets/ogre64.z64, docs/class-catalog.md)

Tables (all in `.streamedB` data, ROM = vram - 0x8016AF80 + 0x40E80):

  class table   0x80187C34 + c*0x48     (func_8016DE3C reads +0x04 size)
  attack table  ROM 0x6099C + a*0x10    (name pointer, kind, element, target, ...)
  item table    ROM 0x6232C + i*0x20    (name pointer first)

Class record fields used here:

  +0x00  name pointer
  +0x04  size (1 normal, 2 large)
  +0x05  body (0 male, 1 female, 2 beast/neuter, 3 NPC, 4 undead/spirit)
  +0x06  tier (0 base, 1 advanced, 2 special)
  +0x08  seven stats, 4 bytes each: [0, base, growth, 0]
         order HP, STR, VIT, INT, MEN, AGI, DEX
  +0x23  nine bytes, 50 = neutral: R0 ?, R1 default alignment, R2 ?,
         R3..R6 wind/flame/earth/water resistance (?), R7 virtue, R8 bane
  +0x2C  movement type (1 = flying: Angel, Hawkman, Faerie, Ghost, Vultan)
  +0x2E  four default equipment item ids (u16)
  +0x37  attacks per row: (attack id, count) for front, middle, back
  +0x41  gender lock (2 male, 4 female, 0 any)
  +0x43  the class this one promotes from, +0x44 its level gate

Field meanings marked "?" are inferred from patterns across classes and not
yet confirmed by the code that reads them.
"""

import struct
import sys

ROM_PATH = sys.argv[1] if len(sys.argv) > 1 else "assets/ogre64.z64"
OUT_PATH = sys.argv[2] if len(sys.argv) > 2 else "docs/class-catalog.md"

rom = open(ROM_PATH, "rb").read()


def rom_of(vram):
    return vram - 0x8016AF80 + 0x40E80


def c_string(vram):
    off = rom_of(vram)
    end = rom.index(b"\0", off)
    return rom[off:end].decode("latin1").replace("\x81", " ")


def u16(off):
    return struct.unpack(">H", rom[off:off + 2])[0]


def u32(off):
    return struct.unpack(">I", rom[off:off + 4])[0]


def valid_ptr(p):
    return 0x80180000 <= p < 0x80192000


ATTACK_BASE = 0x6099C
ITEM_BASE = 0x6232C
CLASS_BASE = 0x80187C34
CLASS_STRIDE = 0x48
CLASS_COUNT = 165

KIND = {0: "melee", 1: "ranged", 3: "spell", 4: "special", 5: "breath"}
ELEMENT = {0: "phys", 1: "wind", 2: "flame", 3: "earth", 4: "water", 5: "virtue", 6: "bane",
           7: "omni", 8: "by gear"}
BODY = {0: "male", 1: "female", 2: "beast", 3: "npc", 4: "undead"}
STATS = ["HP", "STR", "VIT", "INT", "MEN", "AGI", "DEX"]


def attack(a):
    off = ATTACK_BASE + a * 0x10
    p = u32(off)
    name = c_string(p) if valid_ptr(p) else ""
    kind = rom[off + 4]
    elem = rom[off + 5]
    target = rom[off + 6]
    if not name:
        name = "magic" if kind == 3 else "special"
    return name, KIND.get(kind, str(kind)), ELEMENT.get(elem, str(elem)), target


def item(i):
    if i == 0:
        return "-"
    off = ITEM_BASE + i * 0x20
    p = u32(off)
    return c_string(p) if valid_ptr(p) else f"item {i}"


classes = []
for c in range(1, CLASS_COUNT):
    off = rom_of(CLASS_BASE + c * CLASS_STRIDE)
    r = rom[off:off + CLASS_STRIDE]
    p = struct.unpack(">I", r[:4])[0]
    if not valid_ptr(p):
        break
    stats = [(r[8 + 4 * i + 1], r[8 + 4 * i + 2]) for i in range(7)]
    rows = []
    for i in range(3):
        a, n = r[0x37 + 2 * i], r[0x38 + 2 * i]
        rows.append((a, n))
    classes.append({
        "id": c,
        "name": c_string(p),
        "size": r[4],
        "body": BODY.get(r[5], str(r[5])),
        "tier": r[6],
        "stats": stats,
        "resist": list(r[0x23:0x2C]),
        "element": r[0x2C],
        "equip": [struct.unpack(">H", r[0x2E + 2 * i:0x30 + 2 * i])[0] for i in range(4)],
        "rows": rows,
        "gender": {2: "M", 4: "F"}.get(r[0x41], "-"),
        "from": r[0x43],
        "gate": r[0x44],
    })

by_id = {c["id"]: c for c in classes}
children = {}
for c in classes:
    if c["from"] not in (0, 0xFF) and c["from"] in by_id:
        children.setdefault(c["from"], []).append(c["id"])


def row_text(a, n):
    if n == 0 or n > 9:
        return "-"
    name, kind, elem, target = attack(a)
    extra = f" {elem}" if elem not in ("phys",) else ""
    return f"{name} x{n} ({kind}{extra}, t{target})"


out = []
out.append("# Class catalog\n")
out.append("Generated by `tools/class_catalog.py` from the ROM. Do not edit by hand.\n")
out.append("Stats are level-1 base values with per-level growth in parentheses. Rows are\n"
           "front / middle / back: attack name, count, kind, element and target pattern\n"
           "(`t1` single target; higher values hit more targets). Resistances are nine\n"
           "bytes where 50 is neutral; their order is not yet confirmed (R0..R8).\n")

out.append("\n## Summary\n")
out.append("| id | class | body | size | tier | stat total | growth total | best row | promotes from | promotes to |")
out.append("|---|---|---|---|---|---|---|---|---|---|")
for c in classes:
    total = sum(b for b, g in c["stats"])
    growth = sum(g for b, g in c["stats"])
    counts = [n if n <= 9 else 0 for a, n in c["rows"]]
    best = ["front", "middle", "back"][counts.index(max(counts))] if max(counts) else "-"
    frm = by_id[c["from"]]["name"] + f" (L{c['gate']})" if c["from"] in by_id else "-"
    to = ", ".join(by_id[k]["name"] for k in children.get(c["id"], [])) or "-"
    out.append(f"| {c['id']} | {c['name']} | {c['body']} | {c['size']} | {c['tier']} | {total} | "
               f"{growth} | {best} | {frm} | {to} |")

out.append("\n## Detail\n")
for c in classes:
    stats = ", ".join(f"{s} {b} (+{g})" for s, (b, g) in zip(STATS, c["stats"]))
    out.append(f"### {c['id']}. {c['name']}\n")
    out.append(f"- body {c['body']}, size {c['size']}, tier {c['tier']}, gender lock {c['gender']}, "
               f"movement type {c['element']}")
    out.append(f"- {stats}")
    out.append(f"- front: {row_text(*c['rows'][0])}")
    out.append(f"- middle: {row_text(*c['rows'][1])}")
    out.append(f"- back: {row_text(*c['rows'][2])}")
    r = c["resist"]
    out.append(f"- alignment {r[1]}, virtue {r[7]}, bane {r[8]}; other bytes R0 {r[0]}, R2 {r[2]}, "
               f"R3..R6 {r[3]} {r[4]} {r[5]} {r[6]}")
    out.append(f"- default gear: {', '.join(item(i) for i in c['equip'])}\n")

open(OUT_PATH, "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"{len(classes)} classes -> {OUT_PATH}")

